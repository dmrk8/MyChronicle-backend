from datetime import datetime, timedelta, timezone
from jose import JWTError, jwt
from typing import Optional
from app.models.auth.jwt_models import Claims


class JWTHandler:
    SECONDS_PER_DAY = 86400

    def __init__(
        self,
        secret: str,
        algorithm: str,
        issuer: str,
        audience: str,
        expire_days: int,
    ):
        self.secret_key = secret
        self.algorithm = algorithm
        self.issuer = issuer
        self.audience = audience
        self.expire_days = expire_days

        if not self.secret_key:
            raise ValueError("SECRET_KEY is required")
        if not self.algorithm:
            raise ValueError("ALGORITHM is required")
        if not self.issuer:
            raise ValueError("ISSUER is required")
        if not self.audience:
            raise ValueError("AUDIENCE is required")

    def encode_token(self, claims: Claims) -> str:
        """_summary_
            encodes the token using claims
        Args:
            claims (Claims): _description_

        Returns:
            str: token generated by claims
        """

        to_encode = claims.model_dump()

        encoded_jwt = jwt.encode(to_encode, self.secret_key, algorithm=self.algorithm)

        return encoded_jwt

    def decode_token(self, token: str) -> Optional[Claims]:
        if not token:
            return None
        try:
            payload_dict = jwt.decode(
                token,
                self.secret_key,
                algorithms=[self.algorithm],
                audience=self.audience,
                issuer=self.issuer,
            )

            return Claims(**payload_dict)
        except JWTError:
            return None

    def generate_claims(
        self, user_id: str, expires_delta: Optional[timedelta] = None
    ) -> Claims:
        if expires_delta:
            expire = datetime.now(timezone.utc) + expires_delta
        else:
            expire = datetime.now(timezone.utc) + timedelta(days=self.expire_days)

        return Claims(
            sub=user_id,
            exp=int(expire.timestamp()),
            iss=self.issuer,
            aud=self.audience,
        )


